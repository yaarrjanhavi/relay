def build_eval_prompts() -> None:
    prompts_list = []
    idx = 1
    for cat, items in PROMPTS.items():
        for prompt in items:
            prompts_list.append(
                {
                    "id": f"eval-{idx:03d}",
                    "prompt": prompt,
                    "category": cat,
                    "source": "Relay Benchmark Suite (adapted from HumanEval, GSM8K, CNN/DM, UltraChat, MedLegal)",
                }
            )
            idx += 1

    os.makedirs("data", exist_ok=True)
    out_path = os.path.join("data", "eval_prompts.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(prompts_list, f, indent=2)

    print(f"Generated {len(prompts_list)} eval prompts in {out_path}")


if __name__ == "__main__":
    build_eval_prompts()
